    /*
     * ---------------------------------------------------------------------
     * MARK BATCH READY FOR DATA ENTRY
     * ---------------------------------------------------------------------
     */
    @Override
    public boolean markBatchReadyForDataEntry(
            long batchId,
            long userId) {

        if (batchId <= 0L
                || userId <= 0L) {

            return false;
        }


        Connection connection = null;


        try {

            connection =
                    ConnectionPool
                            .getDataSource()
                            .getConnection();

            connection.setAutoCommit(false);


            /*
             * ---------------------------------------------------------
             * 1. Mark applicable cheques as DATA_ENTRY.
             *
             * RETURN_BY_MAKER cheques are excluded.
             *
             * DATA_ENTRY cheques are also excluded so that this
             * operation is idempotent.
             * ---------------------------------------------------------
             */
            String chequeStatusSql =
                    """
                    INSERT INTO public.inward_cheque_status_history
                    (
                        cheque_number,
                        status,
                        rejection_reason_code,
                        return_reason_code,
                        maker_id,
                        maker_action,
                        maker_action_on,
                        checker_id,
                        checker_action,
                        checker_action_on,
                        remarks
                    )
                    SELECT
                        c.cheque_number,
                        'DATA_ENTRY',
                        NULL,
                        NULL,
                        ?,
                        'MICR_STAGE_COMPLETED',
                        CURRENT_TIMESTAMP,
                        NULL,
                        NULL,
                        NULL,
                        'Cheque ready for Data Entry'
                    FROM public.inward_cheque c
                    LEFT JOIN LATERAL
                    (
                        SELECT
                            h.status
                        FROM public.inward_cheque_status_history h
                        WHERE h.cheque_number =
                                c.cheque_number
                        ORDER BY
                            h.status_history_id DESC
                        LIMIT 1
                    ) latest
                        ON TRUE
                    WHERE c.batch_id = ?
                      AND COALESCE(
                            latest.status,
                            ''
                          ) NOT IN (
                            'RETURN_BY_MAKER',
                            'DATA_ENTRY',
                            'DATA_ENTRY_COMPLETED',
                            'SENT_TO_CHECKER'
                          )
                    """;


            try (
                    PreparedStatement statement =
                            connection.prepareStatement(
                                    chequeStatusSql)
            ) {

                statement.setLong(
                        1,
                        userId);

                statement.setLong(
                        2,
                        batchId);

                statement.executeUpdate();
            }


            /*
             * ---------------------------------------------------------
             * 2. Check the latest batch status.
             * ---------------------------------------------------------
             */
            String latestBatchStatusSql =
                    """
                    SELECT batch_status
                    FROM public.inward_batch_history
                    WHERE batch_id = ?
                    ORDER BY
                        batch_history_id DESC
                    LIMIT 1
                    """;


            String latestBatchStatus = null;


            try (
                    PreparedStatement statement =
                            connection.prepareStatement(
                                    latestBatchStatusSql)
            ) {

                statement.setLong(
                        1,
                        batchId);


                try (
                        ResultSet resultSet =
                                statement.executeQuery()
                ) {

                    if (resultSet.next()) {

                        latestBatchStatus =
                                resultSet.getString(
                                        "batch_status");
                    }
                }
            }


            /*
             * ---------------------------------------------------------
             * 3. Move batch to DATA_ENTRY.
             *
             * Do not create duplicate DATA_ENTRY records.
             * ---------------------------------------------------------
             */
            if (!"DATA_ENTRY".equalsIgnoreCase(
                    latestBatchStatus)) {

                String batchHistorySql =
                        """
                        INSERT INTO public.inward_batch_history
                        (
                            batch_id,
                            batch_status,
                            changed_on,
                            changed_by,
                            reason,
                            remarks
                        )
                        VALUES
                        (
                            ?,
                            'DATA_ENTRY',
                            CURRENT_TIMESTAMP,
                            ?,
                            'MICR validation completed',
                            'Batch ready for Data Entry'
                        )
                        """;


                try (
                        PreparedStatement statement =
                                connection.prepareStatement(
                                        batchHistorySql)
                ) {

                    statement.setLong(
                            1,
                            batchId);

                    statement.setLong(
                            2,
                            userId);


                    int inserted =
                            statement.executeUpdate();


                    if (inserted != 1) {

                        connection.rollback();

                        return false;
                    }
                }
            }


            connection.commit();

            return true;


        } catch (SQLException e) {

            if (connection != null) {

                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    rollbackException.printStackTrace();
                }
            }


            throw new RuntimeException(
                    "Failed to move batch "
                            + batchId
                            + " to DATA_ENTRY",
                    e);


        } finally {

            if (connection != null) {

                try {

                    connection.setAutoCommit(true);
                    connection.close();

                } catch (SQLException closeException) {

                    closeException.printStackTrace();
                }
            }
        }
    }
