    /*
     * ---------------------------------------------------------------------
     * SAVE MAKER RETURN
     * ---------------------------------------------------------------------
     *
     * This performs:
     *
     * 1. Insert return request
     * 2. Insert RETURN_BY_MAKER status history
     * 3. Check remaining MICR_MISMATCH cheques
     * 4. If none remain, insert DATA_ENTRY batch history
     * ---------------------------------------------------------------------
     */
    @Override
    public boolean saveMakerReturn(
            String chequeNumber,
            String returnReasonCode,
            String makerRemarks,
            long userId) {

        Connection connection = null;

        try {

            connection =
                    ConnectionPool
                            .getDataSource()
                            .getConnection();

            connection.setAutoCommit(false);


            /*
             * ---------------------------------------------------------
             * 1. Save cheque return
             * ---------------------------------------------------------
             */
            String returnSql =
                    "INSERT INTO public.inward_cheque_return "
                    + "(cheque_number, "
                    + "return_reason_code, "
                    + "maker_remarks, "
                    + "requested_by, "
                    + "return_status) "
                    + "VALUES (?, ?, ?, ?, ?)";

            try (PreparedStatement statement =
                         connection.prepareStatement(returnSql)) {

                statement.setString(
                        1,
                        chequeNumber);

                statement.setString(
                        2,
                        returnReasonCode);

                if (makerRemarks == null
                        || makerRemarks.trim().isEmpty()) {

                    statement.setNull(
                            3,
                            Types.VARCHAR);

                } else {

                    statement.setString(
                            3,
                            makerRemarks.trim());
                }

                statement.setLong(
                        4,
                        userId);

                statement.setString(
                        5,
                        STATUS_RETURN_BY_MAKER);

                int inserted =
                        statement.executeUpdate();

                if (inserted != 1) {

                    connection.rollback();
                    return false;
                }
            }


            /*
             * ---------------------------------------------------------
             * 2. Save cheque status history
             * ---------------------------------------------------------
             */
            String historySql =
                    "INSERT INTO public.inward_cheque_status_history "
                    + "(cheque_number, "
                    + "status, "
                    + "rejection_reason_code, "
                    + "return_reason_code, "
                    + "maker_id, "
                    + "maker_action, "
                    + "maker_action_on, "
                    + "checker_id, "
                    + "checker_action, "
                    + "checker_action_on, "
                    + "remarks) "
                    + "VALUES (?, ?, NULL, ?, ?, ?, "
                    + "CURRENT_TIMESTAMP, NULL, NULL, NULL, ?)";

            try (PreparedStatement statement =
                         connection.prepareStatement(historySql)) {

                statement.setString(
                        1,
                        chequeNumber);

                statement.setString(
                        2,
                        STATUS_RETURN_BY_MAKER);

                statement.setString(
                        3,
                        returnReasonCode);

                statement.setLong(
                        4,
                        userId);

                statement.setString(
                        5,
                        STATUS_RETURN_BY_MAKER);

                if (makerRemarks == null
                        || makerRemarks.trim().isEmpty()) {

                    statement.setNull(
                            6,
                            Types.VARCHAR);

                } else {

                    statement.setString(
                            6,
                            makerRemarks.trim());
                }

                int inserted =
                        statement.executeUpdate();

                if (inserted != 1) {

                    connection.rollback();
                    return false;
                }
            }


            /*
             * ---------------------------------------------------------
             * 3. Find batch ID
             * ---------------------------------------------------------
             */
            long batchId = 0L;

            String batchIdSql =
                    "SELECT batch_id "
                    + "FROM public.inward_cheque "
                    + "WHERE cheque_number = ? "
                    + "LIMIT 1";

            try (PreparedStatement statement =
                         connection.prepareStatement(batchIdSql)) {

                statement.setString(
                        1,
                        chequeNumber);

                try (ResultSet resultSet =
                             statement.executeQuery()) {

                    if (resultSet.next()) {

                        batchId =
                                resultSet.getLong(
                                        "batch_id");
                    }
                }
            }

            if (batchId <= 0L) {

                connection.rollback();
                return false;
            }


            /*
             * ---------------------------------------------------------
             * 4. Count remaining MICR mismatches
             *
             * Only the latest status for each cheque is considered.
             * ---------------------------------------------------------
             */
            int pendingMicrCount = 0;

            String pendingMicrSql =
                    """
                    SELECT COUNT(*)
                    FROM public.inward_cheque c
                    INNER JOIN LATERAL
                    (
                        SELECT h.status
                        FROM public.inward_cheque_status_history h
                        WHERE h.cheque_number =
                                c.cheque_number
                        ORDER BY
                            h.status_history_id DESC
                        LIMIT 1
                    ) latest
                        ON TRUE
                    WHERE c.batch_id = ?
                      AND latest.status = 'MICR_REPAIR'
                    """;

            try (PreparedStatement statement =
                         connection.prepareStatement(
                                 pendingMicrSql)) {

                statement.setLong(
                        1,
                        batchId);

                statement.setString(
                        2,
                        STATUS_MICR_MISMATCH);

                try (ResultSet resultSet =
                             statement.executeQuery()) {

                    if (resultSet.next()) {

                        pendingMicrCount =
                                resultSet.getInt(1);
                    }
                }
            }


            /*
             * ---------------------------------------------------------
             * 5. If no MICR mismatch remains, batch becomes DATA_ENTRY
             * ---------------------------------------------------------
             */
            if (pendingMicrCount == 0) {

                String latestBatchStatusSql =
                        "SELECT batch_status "
                        + "FROM public.inward_batch_history "
                        + "WHERE batch_id = ? "
                        + "ORDER BY batch_history_id DESC "
                        + "LIMIT 1";

                String latestBatchStatus = null;

                try (PreparedStatement statement =
                             connection.prepareStatement(
                                     latestBatchStatusSql)) {

                    statement.setLong(
                            1,
                            batchId);

                    try (ResultSet resultSet =
                                 statement.executeQuery()) {

                        if (resultSet.next()) {

                            latestBatchStatus =
                                    resultSet.getString(
                                            "batch_status");
                        }
                    }
                }


                if (!STATUS_DATA_ENTRY.equalsIgnoreCase(
                        latestBatchStatus)) {

                    String batchHistorySql =
                            "INSERT INTO public.inward_batch_history "
                            + "(batch_id, "
                            + "batch_status, "
                            + "changed_on, "
                            + "changed_by, "
                            + "reason, "
                            + "remarks) "
                            + "VALUES (?, ?, CURRENT_TIMESTAMP, ?, ?, ?)";

                    try (PreparedStatement statement =
                                 connection.prepareStatement(
                                         batchHistorySql)) {

                        statement.setLong(
                                1,
                                batchId);

                        statement.setString(
                                2,
                                STATUS_DATA_ENTRY);

                        statement.setLong(
                                3,
                                userId);

                        statement.setString(
                                4,
                                "MICR_REPAIR_COMPLETED");

                        statement.setString(
                                5,
                                "All cheques completed MICR stage; "
                                        + "batch ready for Data Entry");

                        int inserted =
                                statement.executeUpdate();

                        if (inserted != 1) {

                            connection.rollback();
                            return false;
                        }
                    }
                }
            }


            connection.commit();

            return true;

        } catch (SQLException e) {

            if (connection != null) {

                try {
                    connection.rollback();
                } catch (SQLException rollbackException) {
                    rollbackException.printStackTrace();
                }
            }

            throw new RuntimeException(
                    "Failed to save maker return for cheque "
                            + chequeNumber,
                    e);

        } finally {

            if (connection != null) {

                try {
                    connection.setAutoCommit(true);
                    connection.close();
                } catch (SQLException closeException) {
                    closeException.printStackTrace();
                }
            }
        }
    }


